// 탐험형(로어) 모듈 공통 — SCP·백룸이 같이 쓴다.
//
// 뉴스형과 근본이 다르다: 여러 아이템에서 고르는 게 아니라 **문서 한 편**을
// 소개한다. 그래서 프롬프트도 "골라라"가 아니라 "읽게 만들어라"다.
import type { RawItem } from "../types";

/**
 * 안 읽은 로어 카드가 이만큼 있으면 그 회차는 쉰다.
 *
 * 2인 이유: 1이면 읽는 순간 큐가 비어 다음 정시까지 빈손이고, 3부터는
 * 읽을거리가 아니라 밀린 숙제로 보이기 시작한다. 읽으면 한 시간 안에
 * 다음 편이 오는 리듬 — 하루 상한은 MAX_OK_PER_DAY(24)가 그대로 걸린다.
 */
export const LORE_QUEUE_CAP = 2;

export interface LoreBrief {
  /** 세계관 이름 — "SCP 재단", "백룸" */
  world: string;
  /** 입력이 무엇인지 — "SCP 문서 한 편", "레벨 또는 엔티티 문서 한 편" */
  doc: string;
  /** 리드 문단이 답할 질문 (prompt.ts LEAD_ASK와 같은 역할) */
  ask: string;
  /** 카드 불릿 구성 — "**라벨** — 내용 지시" 꼴 */
  bullets: string[];
}

export function lorePrompt(brief: LoreBrief): string {
  return [
    `너는 ${brief.world} 아카이브의 큐레이터다. 읽는 사람은 일하다 잠깐 쉬면서`,
    `"오늘은 뭐가 나왔나" 하고 열어 본다. 뉴스가 아니다 — 오래된 문서여도 좋은 문서면 된다.`,
    "",
    `입력은 ${brief.doc}의 본문 텍스트다(위키에서 그대로 가져와 태그를 벗긴 것이라`,
    "메뉴·평점 같은 잡음이 섞여 있을 수 있다 — 무시해라).",
    "",
    "출력은 두 부분이다.",
    "",
    "1) **리드 문단** 2~3문장, 불릿 없는 평문 한 문단.",
    `   이 문단이 답해야 하는 질문: ${brief.ask}`,
    "   문서 소개말이 아니라 이야기의 훅이어야 한다. \"~를 다룬 문서다\"는 아무것도 안 한 것이다.",
    "   \"리드 문단\" 같은 라벨·소제목을 출력에 쓰지 마라 — 바로 문장으로 시작해라(실측: 라벨을 그대로 박아 카드에 떴다).",
    "",
    "2) 빈 줄 뒤에 마크다운 불릿. 첫 줄은 반드시:",
    "   `- [문서 제목](#1) — 한 줄 정체`",
    "   그다음 아래 구성을 따르되, 문서에 없는 항목은 억지로 만들지 말고 빼라:",
    ...brief.bullets.map((b) => `   - ${b}`),
    "",
    "링크 자리에는 주소 대신 `#1`을 써라. 실제 주소는 코드가 붙인다.",
    "",
    "**전부 한국어.** 원문이 영어면 읽고 자연스러운 한국어로 옮겨라.",
    "요약이 아니라 소개다 — 다 알려주되, 문서를 직접 읽고 싶어지게 써라.",
    "`SKIP`은 **본문이 사실상 없을 때만** 쓴다 — 몇 줄짜리 스텁이거나 삭제 안내뿐일 때.",
    "문서가 실험적이거나 형식이 이상한 건 SKIP 사유가 아니다 — 이런 위키에선 그게 곧",
    "개성이다. 이상하면 이상하다고 소개해라.",
    "인사말·맺음말은 쓰지 마라.",
  ].join("\n");
}

/**
 * 표지 이미지를 본문 맨 앞에 붙인다. 이미지 주소는 코드가 위키에서 가져온 것
 * — 모델에게 URL을 쓰게 하면 지어내거나 자른다.
 */
export function lorePostProcess(content: string, picked: RawItem[]): string {
  const img = picked[0]?.payload?.imageUrl;
  if (typeof img !== "string" || !img) return content;
  return `![표지](${img})\n\n${content}`;
}
